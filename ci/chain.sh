#!/usr/bin/env bash
# เรียกรอบถัดไปมานั่งรอในคิวด้วยตัวเอง แทนที่จะรอ cron
#
# ทำไมต้องมี: ยามของ workflow นี้ไม่ใช่ตัวเวลาของ cron แต่เป็น "รอบที่นั่งรออยู่ในคิว" ตราบใดที่
# คิวมีคนรอ ตัวเก็บที่ตายกลางทางจะถูกรับช่วงทันที วัดตรงที่ช่องโหว่เมื่อ 2026-09-16 — นับจาก
# วินาทีที่ตัวรอถูกเลื่อนขึ้นมาวิ่งจนรอบถัดไปถูกสร้าง — พบว่าคิวว่างเปล่าค่ากลาง 127 นาที สูงสุด
# 288 ทั้งที่ตั้ง cron ไว้ทุก 10 นาที แปลว่าราว 37% ของ job ยาว 5 ชม. 45 นาที ไม่มีใครนั่งรออยู่เลย
# และรอยต่อ 18 จาก 22 จุดกว้างเกินหนึ่งชั่วโมง ถ้าตัวเก็บตายช่วงนั้นช่องว่างยาวได้ถึง 6 ชม.
# การยิง cron ให้ถี่ขึ้นไม่ช่วย เพราะ GitHub เป็นคนตัดสินใจทิ้งรอบเอง ทางที่เหลือคือ job เรียกเอง
#
# ทำไมต้องรอก่อน ไม่เรียกทันทีที่เริ่ม: ถ้าเรียกทันที job ที่พังตั้งแต่ต้น (คีย์หมดอายุ โคลนไม่ผ่าน)
# จะปลุกตัวถัดไปที่พังเหมือนกันทันที กลายเป็นวงวนที่หมุนไม่หยุด การรอให้ตัวเก็บอยู่รอดก่อน
# CHAIN_AFTER วินาทีทำให้วงวนแบบนั้นจบเอง — พังเร็วแปลว่าไม่มีการเรียกต่อ แล้วปล่อยให้ cron
# เป็นตัวกู้ตามจังหวะช้าของมัน ราคาที่จ่ายคือช่วงต้น job เท่านั้นที่ยังไม่มีใครนั่งรอ
#
# โทเคนอัตโนมัติของ Actions เรียก workflow_dispatch ไม่ได้ ต้องใช้ PAT (FM_CHAIN_TOKEN)
# ที่มีสิทธิ์ Actions: read and write บน repo นี้
#
# ล้มเหลวแล้วต้องไม่เงียบ แต่ก็ต้องไม่ฆ่าตัวเก็บ — ใช้แฟ้มร่องรอยแบบเดียวกับ push_loop.sh
set -uo pipefail

CHAIN_AFTER="${CHAIN_AFTER:-600}"

if [ -z "${GH_TOKEN:-}" ]; then
  echo "::warning::ไม่มี FM_CHAIN_TOKEN — รอบนี้จะไม่เรียกรอบถัดไป เหลือ cron เป็นยามตัวเดียว"
  exit 0
fi

sleep "$CHAIN_AFTER"

# ตัวเก็บยังอยู่ไหม ถ้าตายไปแล้วก็ไม่ต้องเรียกใคร — ขั้นตอนปิดท้ายกำลังจะปล่อยคิวให้ cron อยู่แล้ว
if ! pgrep -f collect.py >/dev/null 2>&1; then
  echo "::warning::ตัวเก็บไม่อยู่แล้วตอนครบ ${CHAIN_AFTER} วินาที — ไม่เรียกรอบถัดไป"
  exit 0
fi

if gh workflow run collect.yml --repo "$GITHUB_REPOSITORY" --ref "$GITHUB_REF_NAME" 2>&1 | tee -a "$RUNNER_TEMP/chain.log"; then
  echo "เรียกรอบถัดไปมานั่งรอในคิวแล้ว"
else
  date -u '+%Y-%m-%d %H:%M:%S UTC เรียกรอบถัดไปล้มเหลว' >> "$RUNNER_TEMP/chain-failed"
  tail -20 "$RUNNER_TEMP/chain.log" >> "$RUNNER_TEMP/chain-failed" 2>/dev/null || true
fi
